function currentLang() { return localStorage.getItem('asseto-lang') || 'ru'; }

function t(key) {
  const dict = i18n[currentLang()] || i18n.ru;
  return dict[key] || (i18n.ru[key]) || key;
}

function applyI18n() {
  const dict = i18n[currentLang()] || i18n.ru;
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-t-ph]').forEach(el => {
    const key = el.getAttribute('data-t-ph');
    if (dict[key]) el.placeholder = dict[key];
  });
  document.querySelectorAll('[data-t-title]').forEach(el => {
    const key = el.getAttribute('data-t-title');
    if (dict[key]) el.title = dict[key];
  });
  document.documentElement.setAttribute('lang', currentLang() === 'ru' ? 'ru' : (currentLang() === 'uz' ? 'uz' : 'en'));
}

function setLanguage(lang) {
  localStorage.setItem('asseto-lang', lang);
  document.cookie = 'asseto_lang=' + lang + ';path=/;max-age=31536000';
  applyI18n();
  document.dispatchEvent(new CustomEvent('asseto-lang-changed', { detail: { lang } }));
}

// Обратная совместимость со старым названием, использовавшимся в app.js
function updateI18n() { applyI18n(); }
function setDashLang(l) { setLanguage(l); }

document.addEventListener('DOMContentLoaded', applyI18n);
